  // ==========================================================================
  //  Purchasing: style BOM × selected POs → required quantities
  // ==========================================================================
  // requirement = consumption per garment × pieces of that color × (1 + waste%)
  //   • pieces per color come from work_order_lines (the PO's talla × color grid)
  //   • a fabric uses the yield confirmed on the PO line for that fabric code
  //     when there is one, otherwise the sample-room yield from the style BOM
  //   • the material's color in each colorway comes from the style's colorway
  //     matrix (colorways[].components[lineKey]); falls back to the PO color
  //   • count units (pzs / unid) are rounded up; length/weight to 2 decimals
  const COUNT_UNITS = new Set(["pzs", "pza", "pz", "unid", "u", "pc", "pcs"]);
  const n0 = (v) => { const x = Number(String(v ?? "").replace(",", ".")); return Number.isFinite(x) ? x : 0; };

  function bomLines(d) {
    const out = [];
    for (const f of Array.isArray(d.fabrics) ? d.fabrics : []) {
      if (!f || !(f.name || f.code)) continue;
      out.push({ key: f.key, kind: "fabric", code: f.code || "", name: f.name || f.composition || "", supplier: f.supplier || "",
        unit: f.yieldUnit || "mts", consumption: n0(f.yield), position: f.position || "" });
    }
    const trims = Array.isArray(d.trims) ? d.trims
      : (Array.isArray(d.trimMaterials) ? d.trimMaterials : []).map((t) => ({ ...t, name: t.desc, clientCode: t.code, code: "" }));
    for (const t of trims) {
      if (!t || !(t.name || t.code || t.clientCode)) continue;
      out.push({ key: t.key, kind: "trim", code: t.code || t.clientCode || "", name: t.name || "", supplier: t.supplier || "",
        unit: t.unit || "pzs", consumption: n0(t.consumption ?? t.qty), position: t.placement || "" });
    }
    const pack = Array.isArray(d.packaging) ? d.packaging
      : (Array.isArray(d.packingTrims) ? d.packingTrims : []).map((t) => ({ ...t, name: t.desc, consumption: t.qty }));
    for (const t of pack) {
      if (!t || !(t.name || t.code || t.clientCode)) continue;
      out.push({ key: t.key, kind: "packaging", code: t.code || t.clientCode || "", name: t.name || "", supplier: t.supplier || "",
        unit: t.unit || "pzs", consumption: n0(t.consumption ?? t.qty), position: t.placement || "" });
    }
    return out;
  }

  async function computePurchase(client, so, workOrderIds, wastePct) {
    const d = so.data || {};
    const warnings = [];
    const ids = [...new Set((workOrderIds || []).map(Number).filter((x) => Number.isFinite(x) && x > 0))];
    if (!ids.length) return { lines: [], pieces: 0, workOrders: [], warnings: ["Selecciona al menos una orden de producción."] };

    const wo = await client.query(
      `SELECT id, work_order_no, quantity, color, status FROM work_orders
        WHERE id = ANY($1) AND upper(btrim(style_code)) = $2 ORDER BY work_order_no`,
      [ids, so.style_code]
    );
    if (wo.rows.length !== ids.length) warnings.push("Algunas órdenes no pertenecen a este estilo y se ignoraron.");
    const woIds = wo.rows.map((r) => Number(r.id));

    const ln = woIds.length
      ? (await client.query(`SELECT work_order_id, color, quantity, fabrics FROM work_order_lines WHERE work_order_id = ANY($1)`, [woIds])).rows
      : [];

    // pieces per color, and PO-confirmed fabric yields per color + fabric code
    const pieces = new Map();              // color -> pieces
    const poYield = new Map();             // `${color}|${CODE}` -> { sum: yield×pieces, pieces }
    const withLines = new Set();
    for (const l of ln) {
      const color = String(l.color || "").trim().toUpperCase();
      const q = n0(l.quantity);
      withLines.add(Number(l.work_order_id));
      pieces.set(color, (pieces.get(color) || 0) + q);
      let fabs = l.fabrics;
      if (typeof fabs === "string") { try { fabs = JSON.parse(fabs); } catch { fabs = []; } }
      for (const f of Array.isArray(fabs) ? fabs : []) {
        const y = n0(f?.yield);
        const code = String(f?.code || "").trim().toUpperCase();
        if (!(y > 0) || !code) continue;
        const k = `${color}|${code}`;
        const cur = poYield.get(k) || { sum: 0, pieces: 0 };
        cur.sum += y * q; cur.pieces += q;
        poYield.set(k, cur);
      }
    }
    // POs without a talla × color grid: use their header quantity, color unknown
    for (const r of wo.rows) {
      if (withLines.has(Number(r.id))) continue;
      const color = /^[A-Z0-9]{3}$/i.test(String(r.color || "").trim()) ? String(r.color).trim().toUpperCase() : "";
      pieces.set(color, (pieces.get(color) || 0) + n0(r.quantity));
      warnings.push(`${r.work_order_no} no tiene desglose por color; se usó su cantidad total${color ? "" : " sin color"}.`);
    }
    const totalPieces = [...pieces.values()].reduce((a, b) => a + b, 0);

    const cwByCode = new Map((Array.isArray(d.colorways) ? d.colorways : []).map((c) => [String(c.code || "").toUpperCase(), c]));
    const factor = 1 + (Number(wastePct) || 0) / 100;
    const groups = new Map();
    const noCons = new Set();

    for (const m of bomLines(d)) {
      for (const [poColor, pcs] of pieces) {
        if (!(pcs > 0)) continue;
        const cw = cwByCode.get(poColor);
        const matColor = (cw?.components && m.key && String(cw.components[m.key] || "").trim()) || "";
        let cons = m.consumption;
        let yieldSource = "style";
        if (m.kind === "fabric" && m.code) {
          const py = poYield.get(`${poColor}|${String(m.code).trim().toUpperCase()}`);
          if (py && py.pieces > 0) { cons = py.sum / py.pieces; yieldSource = "po"; }
        }
        if (!(cons > 0)) noCons.add(`${m.code || m.name}`);
        const required = cons * pcs * factor;
        const gk = [m.kind, m.code.toUpperCase(), m.name.toLowerCase(), matColor.toLowerCase(), m.supplier.toLowerCase(), m.unit.toLowerCase()].join("|");
        const g = groups.get(gk) || {
          kind: m.kind, code: m.code, name: m.name, color: matColor, supplier: m.supplier, unit: m.unit, position: m.position,
          poColors: [], consumptions: new Set(), pieces: 0, required: 0, yieldSource,
        };
        g.poColors.push(poColor || "—");
        g.consumptions.add(Math.round(cons * 10000) / 10000);
        g.pieces += pcs;
        g.required += required;
        if (yieldSource === "po") g.yieldSource = "po";
        groups.set(gk, g);
      }
    }
    if (noCons.size) warnings.push(`Sin consumo capturado: ${[...noCons].slice(0, 8).join(", ")}${noCons.size > 8 ? "…" : ""}. Su requerido sale en 0.`);
    if (!cwByCode.size) warnings.push("El estilo no tiene colorways: el color de cada material queda en blanco.");

    const kindRank = { fabric: 0, trim: 1, packaging: 2 };
    const lines = [...groups.values()].map((g) => {
      const isCount = COUNT_UNITS.has(String(g.unit).toLowerCase());
      const required = isCount ? Math.ceil(g.required - 1e-9) : Math.round(g.required * 100) / 100;
      const cons = [...g.consumptions];
      return {
        kind: g.kind, code: g.code, name: g.name, color: g.color, supplier: g.supplier, unit: g.unit, position: g.position,
        poColors: [...new Set(g.poColors)],
        consumption: cons.length === 1 ? cons[0] : null,   // null = varies by color
        yieldSource: g.yieldSource,
        pieces: Math.round(g.pieces),
        required,
      };
    }).sort((a, b) =>
      (a.supplier || "~").localeCompare(b.supplier || "~", "es") || (kindRank[a.kind] - kindRank[b.kind]) ||
      a.code.localeCompare(b.code) || a.color.localeCompare(b.color));

    return {
      lines,
      pieces: Math.round(totalPieces),
      piecesByColor: Object.fromEntries([...pieces].map(([c, q]) => [c || "—", Math.round(q)])),
      workOrders: wo.rows.map((r) => ({ id: Number(r.id), no: r.work_order_no, quantity: n0(r.quantity), color: r.color, status: r.status })),
      warnings,
    };
  }

